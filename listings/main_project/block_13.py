# 1. Лингвистический калькулятор посимвольного совпадения слов (аналог BLEU-1)
def calculate_simple_bleu(reference: str, candidate: str) -> float:
    def to_clean_words(text_str):
        for char in ['{', '}', '"', ',', ':', '[', ']']:
            text_str = text_str.replace(char, '')
        return text_str.lower().split()

    ref_words = to_clean_words(reference)
    cand_words = to_clean_words(candidate)

    if not cand_words:
        return 0.0

    matches = sum(1 for word in cand_words if word in ref_words)
    return matches / len(cand_words)

